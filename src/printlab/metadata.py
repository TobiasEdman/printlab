"""model.yaml: what a design or library model is, how to slice it and how its prints went.

Designs (designs/<slug>/) are generated by a build script; library models
(library/<slug>/) are files from elsewhere and must record where they came from
and under which licence. Both share the ``slice`` and ``prints`` sections.
"""

from __future__ import annotations

import datetime
import re
from pathlib import Path

import yaml

from printlab.paths import ROOT

FILE = "model.yaml"
REQUIRED = {
    "designs": ("name", "description", "build", "outputs"),
    "library": ("name", "description", "source", "author", "licence", "files"),
}
SLICE_KEYS = {"machine", "process", "filaments", "parts", "extruders", "settings", "output",
              "assemble", "copies"}
PRINT_RESULTS = {"ok", "partial", "failed"}
OUTPUT_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9._-]*")  # stays inside build/, no paths


def kind(model_dir: Path) -> str:
    return Path(model_dir).resolve().relative_to(ROOT).parts[0]


def load(model_dir: Path) -> dict:
    return yaml.safe_load((Path(model_dir) / FILE).read_text()) or {}


def all_models(root: Path = ROOT) -> list[Path]:
    return sorted(p.parent for top in REQUIRED for p in (root / top).glob(f"*/{FILE}"))


def validate(model_dir: Path, data: dict, model_kind: str) -> list[str]:
    """Problems with one model.yaml; an empty list means it is valid."""
    model_dir = Path(model_dir)
    errors = [f"missing {k}" for k in REQUIRED[model_kind] if not data.get(k)]
    if model_kind == "designs" and data.get("build"):
        if not (model_dir / data["build"]).exists():
            errors.append(f"build script {data['build']} not found")
    if model_kind == "library":
        for name in data.get("files") or []:
            if not (model_dir / name).exists():
                errors.append(f"listed file {name} not found")
        source = str(data.get("source", ""))
        if source and source != "unknown" and not source.startswith(("http://", "https://")):
            errors.append("source must be a URL or 'unknown'")
    if isinstance(data.get("slice"), list):  # variants, e.g. one per material
        outputs = [v.get("output") for v in data["slice"] if isinstance(v, dict)]
        named = len(outputs) == len(data["slice"]) and None not in outputs
        # Case-insensitive: ABS and abs would overwrite each other on macOS.
        if not data["slice"]:
            errors.append("slice: the variant list is empty")
        elif not named or len({str(o).lower() for o in outputs}) < len(outputs):
            errors.append("slice: every variant needs its own output name")
        for i, variant in enumerate(data["slice"]):
            errors += [f"slice[{i}]: {e}" for e in validate_slice(variant, data, model_kind)]
    elif "slice" in data:
        errors += [f"slice: {e}" for e in validate_slice(data["slice"], data, model_kind)]
    listed = data.get("outputs" if model_kind == "designs" else "files") or []
    for i, scene in enumerate(data.get("view") or []):
        if not scene.get("title") or not isinstance(scene.get("parts"), dict):
            errors.append(f"view[{i}]: needs title and parts (file: colour)")
            continue
        errors += [f"view[{i}]: {p} is not listed" for p in scene["parts"] if p not in listed]
    for i, entry in enumerate(data.get("prints") or []):
        if not isinstance(entry, dict):
            errors.append(f"prints[{i}] is not a mapping")
            continue
        if not isinstance(entry.get("date"), datetime.date):
            errors.append(f"prints[{i}]: date must be YYYY-MM-DD")
        if entry.get("result") not in PRINT_RESULTS:
            errors.append(f"prints[{i}]: result must be one of {sorted(PRINT_RESULTS)}")
        if not entry.get("filament"):
            errors.append(f"prints[{i}]: missing filament")
    return errors


def validate_slice(s: dict, data: dict, model_kind: str) -> list[str]:
    if not isinstance(s, dict):
        return ["must be a mapping"]
    errors = [f"unknown key {k}" for k in set(s) - SLICE_KEYS]
    errors += [f"missing {k}" for k in ("machine", "process", "filaments", "parts", "extruders")
               if not s.get(k)]
    if errors:
        return errors
    n = len(s["filaments"])
    if len(s["extruders"]) != n:
        errors.append("extruders needs one entry (1 left, 2 right) per filament")
    if any(e not in (1, 2) for e in s["extruders"]):
        errors.append("extruders must be 1 (left) or 2 (right)")
    listed = "outputs" if model_kind == "designs" else "files"
    for part, slot in s["parts"].items():
        if part not in (data.get(listed) or []):
            errors.append(f"part {part} is not in {listed}")
        if not isinstance(slot, int) or not 1 <= slot <= n:
            errors.append(f"part {part}: filament slot must be 1..{n}")
    if not isinstance(s.get("settings", {}), dict):
        errors.append("settings must be a mapping")
    if not isinstance(s.get("assemble", False), bool):
        errors.append("assemble must be true or false")
    copies = s.get("copies", 1)
    if isinstance(copies, bool) or not isinstance(copies, int) or copies < 1:
        errors.append("copies must be a whole number, at least 1")
    elif copies > 1 and s.get("assemble"):
        errors.append("copies cannot be combined with assemble")
    if "output" in s and not OUTPUT_NAME.fullmatch(str(s["output"])):
        errors.append("output must be a plain file name (letters, digits, . _ -)")
    return errors
